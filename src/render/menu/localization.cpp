	void set( id value )
	{
		if ( value >= id::en && value < id::count )
		{
			g_current.store( value, std::memory_order_relaxed );
		}
	}

	id current( )
	{
		return g_current.load( std::memory_order_relaxed );
	}

	const char* code( id value )
	{
		return value == id::ru ? "RU" : "EN";
	}

	const char* tr( const char* english )
	{
		if ( !english || current( ) == id::en )
		{
			return english;
		}

		const auto& table = russian( );
		const auto it = table.find( std::string_view{ english } );
		return it == table.end( ) ? english : it->second;
	}

	std::string_view tr( std::string_view english )
	{
		if ( current( ) == id::en )
		{
			return english;
		}

		const auto& table = russian( );
		const auto it = table.find( english );
		return it == table.end( ) ? english : std::string_view{ it->second };
	}

